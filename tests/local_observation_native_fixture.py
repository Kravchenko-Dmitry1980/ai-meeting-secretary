def write_json(path, value):
    with path.open("x", encoding="utf-8") as stream:
        json.dump(value, stream, ensure_ascii=True, indent=2, sort_keys=True)
        stream.flush()
        os.fsync(stream.fileno())


def file_hash(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def loopback_port():
    for _ in range(10):
        with socket.socket() as listener:
            listener.bind(("127.0.0.1", 0))
            port = listener.getsockname()[1]
        if port != 8765:
            return port
    raise RuntimeError("distinct_fixture_port_unavailable")


def prepare_data(data_dir):
    """Use the existing task-assignment repository contract, never a cloud call."""
    from secretary.settings import Settings
    from secretary.infrastructure.database import Database
    from secretary.infrastructure.budget_repository import BudgetRepository
    from secretary.infrastructure.speaker_repository import SpeakerRepository
    from secretary.infrastructure.assignment_repository import AssignmentRepository
    from secretary.application.worker import Worker
    from secretary.application.evidence import validate_summary
    from secretary.domain.models import TranscriptSegment
    from secretary.domain.speakers import AddParticipant, ReviewAttribution
    from secretary.domain.summary_context import ReviewTaskAssignments
    # This helper writes one tiny generated WAV, without devices or user media.
    from test_backend import prepared

    settings = Settings(_env_file=None, data_dir=data_dir, project_dir=ROOT,
                        polza_api_key="", cloud_enabled=False)
    database = Database(data_dir / "secretary.sqlite3")
    BudgetRepository(data_dir / "billing.sqlite3")
    meeting, chunk = prepared(database, settings)
    # The unit helper deliberately uses a placeholder digest. A real backup
    # verifies the actual generated bytes, so fix only this synthetic record.
    database.execute("UPDATE chunks SET sha256=? WHERE id=?",
                     (file_hash(Path(chunk["path"])), chunk["id"]))
    version = database.ensure_version(meeting["id"])
    stt = database.enqueue(meeting["id"], "transcribe", chunk_id=chunk["id"], version=version)
    segments = []
    for index in range(3):
        segments.append(TranscriptSegment(id=f"synthetic-segment-{index}", meeting_id=meeting["id"],
            transcript_version=version, chunk_id=chunk["id"], ordinal=index,
            text=f"Я подготовлю синтетический отчёт номер {index + 1}", channel="import",
            timing_precision="unknown").model_dump())
    database.save_segments(stt, segments, [])
    speakers = SpeakerRepository(database)
    roster = speakers.add_participant(meeting["id"], AddParticipant(display_name="Synthetic participant",
        aliases=[], expected_roster_revision=0, operation_id="synthetic-participant"))
    participant = roster.participants[0].id
    speakers.review_attribution(meeting["id"], ReviewAttribution(transcript_version=version,
        expected_revision=0, operation_id="synthetic-attribution",
        changes=[{"segment_id": row["id"], "participant_id": participant} for row in segments]))

    def provider_forbidden(*_):
        raise AssertionError("No provider calls are allowed in the native fixture")

    worker = Worker(database, settings, provider_forbidden)
    summary_job = worker.enqueue_summary(meeting["id"])
    draft = {"overview": "Synthetic native observation fixture", "decisions": [], "open_questions": [],
        "readable_transcript": "\n".join(row["text"] for row in segments),
        "action_items": [{"text": f"Подготовить синтетический отчёт номер {index + 1}",
            "owner": None, "due_date": None, "source_segment_ids": [row["id"]],
            "evidence_quote": row["text"], "assignment_proposal": {"basis": "self_commitment",
            "semantic_flag": "explicit_commitment", "named_owner_text": None,
            "commitment_segment_id": row["id"]}} for index, row in enumerate(segments)]}
    database.save_summary(summary_job, validate_summary(draft, meeting["id"], version, segments))
    repository = AssignmentRepository(database)
    snapshot = repository.get(meeting["id"])
    reviewed = repository.review(meeting["id"], ReviewTaskAssignments.model_validate({
        "transcript_version": snapshot.transcript_version, "summary_version": snapshot.summary_version,
        "attribution_revision": snapshot.attribution_revision, "roster_revision": snapshot.roster_revision,
        "expected_revision": snapshot.revision, "operation_id": "synthetic-task-confirmation",
        "changes": [{"action_id": item.action.action_id, "decision": "set_manual",
                     "participant_id": participant} for item in snapshot.items]})).current
    assert len(reviewed.items) == 3 and all(item.status == "confirmed" for item in reviewed.items)
    assert not database.rows("SELECT id FROM usage")
    assert not database.rows("SELECT id FROM jobs WHERE status!='succeeded'")
    return [{"meeting_id": meeting["id"], "transcript_version": reviewed.transcript_version,
             "summary_version": reviewed.summary_version, "assignment_revision": reviewed.revision,
             "action_id": item.action.action_id} for item in reviewed.items]


def environment():
    allowed = {"PATH", "SYSTEMROOT", "WINDIR", "TEMP", "TMP", "PATHEXT", "COMSPEC",
               "APPDATA", "LOCALAPPDATA", "USERPROFILE", "HOMEDRIVE", "HOMEPATH"}
    value = {key: item for key, item in os.environ.items() if key.upper() in allowed}
    value.update(PYTHONUTF8="1", PYTHONNOUSERSITE="1", PYTHONPATH=str(ROOT / "backend"))
    return value


def start_supervisor(base, runtime, data_dir, port):
    command = [str(PYTHON), "-B", str(ROOT / "scripts/local_supervisor.py"), "run",
               "--data-dir", str(data_dir), "--port", str(port), "--runtime-root", str(runtime)]
    with (base / "supervisor.stdout.log").open("xb") as out, (base / "supervisor.stderr.log").open("xb") as err:
        return subprocess.Popen(command, cwd=ROOT, env=environment(), stdin=subprocess.DEVNULL,
            stdout=out, stderr=err, creationflags=subprocess.CREATE_NO_WINDOW)


def wait_running(supervisor, process, runtime, candidate):
    deadline = time.monotonic() + 45
    while time.monotonic() < deadline:
        state = supervisor.read_state(runtime)
        if state and state.get("state") == "running":
            assert state["candidate_binding"] == candidate
            assert state["candidate_binding_verified"] is True
            assert state["candidate_binding_reason"] == "verified"
            return state
        if process.poll() is not None:
            raise RuntimeError("synthetic_supervisor_exited_before_ready")
        time.sleep(.05)
    raise RuntimeError("synthetic_supervisor_readiness_timeout")


def cleanup(supervisor, process, runtime):
    from secretary.infrastructure.team_process_identity import process_identity, verify_dead_identity
    state = supervisor.read_state(runtime)
    if state is None:
        if process.poll() is None:
            # Keep the exact handle visible to the caller; never retry or guess
            # a PID when no identity receipt has been published.
            return {"state": "blocked", "code": "live_fixture_owner_without_receipt", "launcher_pid": process.pid}
        return {"state": "exited_before_receipt", "returncode": process.returncode}
    forced = False
    try:
        result = supervisor.request_stop(runtime)
        process.wait(timeout=5)
    except Exception:
        # Only a fresh identity bound to our Popen ancestry authorizes this
        # emergency cleanup of synthetic processes. The owner Job contains apps.
        record = state["supervisor_identity"]
        if process_identity(record["pid"]) != record:
            raise RuntimeError("fixture_cleanup_identity_changed")
        target = psutil.Process(record["pid"])
        if record["pid"] != process.pid and process.pid not in [item.pid for item in target.parents()]:
            raise RuntimeError("fixture_cleanup_ownership_unverified")
        target.kill()
        process.wait(timeout=5)
        forced = True
        result = {"state": "forced_synthetic_cleanup"}
    deadline = time.monotonic() + 5
    records = [state["supervisor_identity"], *state.get("attempt_identities", [])]
    while time.monotonic() < deadline:
        try:
            for record in records:
                verify_dead_identity(record)
            return {**result, "forced": forced, "all_known_processes_dead": True}
        except ValueError as exc:
            if str(exc) != "process_still_alive":
                raise
        time.sleep(.1)
    raise RuntimeError("synthetic_child_survived_cleanup")


def cli():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run", action="store_true", required=True)
    parser.parse_args()
    if not __debug__:
        parser.error("Optimized Python is not supported for native acceptance")
    if os.name != "nt":
        parser.error("Windows is required")
    if os.environ.get("SECRETARY_OFFLINE_RETENTION_RUN"):
        parser.error("Run this fixture explicitly outside the offline pytest guard")
    sys.path.insert(0, str(ROOT / "scripts"))
    sys.path.insert(0, str(ROOT / "tests"))
    import local_supervisor as supervisor
    import local_observation as observation
    from local_candidate import capture_candidate
    from secretary.infrastructure.local_backup import create_backup, verify_backup

    candidate = capture_candidate(ROOT)
    if candidate.get("state") != "bound":
        parser.error("A clean committed candidate and built frontend are required")
    base = supervisor.runtime_path(ROOT / ".runtime" / ("p6-native-" + uuid4().hex))
    base.mkdir()
    data_dir, runtime = base / "data", base / "owner"
    data_dir.mkdir()
    runtime.mkdir()
    print(f"Fixture: {base}", flush=True)
    receipt = {"synthetic": True, "production_qualified": False, "candidate": candidate}
    process = None
    main_state = ROOT / ".runtime/processes.json"
    before_main = file_hash(main_state) if main_state.exists() else None
    main_healthy = False
    with httpx.Client(timeout=2, trust_env=False) as client:
        try:
            main_healthy = client.get("http://127.0.0.1:8765/health").json().get("status") == "ok"
        except (httpx.HTTPError, ValueError):
            pass
    try:
        accepted = prepare_data(data_dir)
        backup = base / "backup"
        create_backup(data_dir, backup)
        verification = verify_backup(backup)
        verify_path = base / "backup-verification.json"
        write_json(verify_path, verification)
        acceptance_path = base / "synthetic-owner-acceptance.json"
        write_json(acceptance_path, {"schema_version": 1, "scope": "local_offline", "synthetic": True,
            "accepted_gates": ["P1", "P2", "P3", "P4", "P5"], "accepted_tasks": accepted})
        port = loopback_port()
        process = start_supervisor(base, runtime, data_dir, port)
        ready = wait_running(supervisor, process, runtime, candidate)
        receipt["startup_binding_verified"] = ready["candidate_binding_verified"]
        config = {"schema_version": 1, "scope": "local_offline", "candidate": candidate,
            "origin": f"http://127.0.0.1:{port}", "data_dir": str(data_dir), "runtime_root": str(runtime),
            "interval_seconds": 5, "max_gap_seconds": 10, "accepted_tasks": accepted,
            "owner_acceptance": {"path": str(acceptance_path), "sha256": file_hash(acceptance_path)},
            "backup": {"directory": str(backup), "manifest_sha256": file_hash(backup / "manifest.json"),
                "verify_receipt": str(verify_path), "verify_receipt_sha256": file_hash(verify_path),
                "excluded_directories": []}}
        config_path, output = base / "observation-input.json", base / "observation"
        write_json(config_path, config)
        cli_stdout = io.StringIO()
        with redirect_stdout(cli_stdout):
            code = observation.main(["observe", "--config", str(config_path), "--output", str(output),
                                     "--duration-seconds", "5"])
        receipt["observer_cli_exit_code"] = code
        raw_cli_report = cli_stdout.getvalue()
        if len(raw_cli_report) > 65536:
            raise RuntimeError("observer_cli_report_bound_exceeded")
        cli_report = json.loads(raw_cli_report)
        if not isinstance(cli_report, dict):
            raise RuntimeError("observer_cli_report_invalid")
        receipt["observer_cli_report"] = cli_report
        report_path = output / "report.json"
        if not report_path.is_file():
            receipt.update(observation_status=cli_report.get("status"),
                           observation_issues=cli_report.get("issues", []),
                           observation_report_missing=True)
            raise RuntimeError("observer_report_missing")
        report = json.loads(report_path.read_text(encoding="utf-8"))
        assert code == 2, code
        assert report["status"] == "INCOMPLETE", report
        assert report["issues"] == ["full_day_not_observed"], report
        assert report["elapsed_seconds"] >= 5
        assert report["production_qualified"] is False
        assert report["synthetic_owner_acceptance"] is True
        assert observation.evaluate_directory(output) == report
        receipt.update(technical_integration="PASS", observation_status=report["status"],
            observation_issues=report["issues"], sample_count=report["sample_count"],
            elapsed_seconds=report["elapsed_seconds"], accepted_task_count=len(accepted),
            synthetic_owner_acceptance=True, observation_report_sha256=file_hash(output / "report.json"))
    except BaseException as exc:
        receipt.update(technical_integration="FAILED", failure_type=type(exc).__name__)
        raise
    finally:
        cleanup_error = None
        try:
            if process is not None:
                receipt["cleanup"] = cleanup(supervisor, process, runtime)
                if receipt["cleanup"].get("state") != "stopped" or receipt["cleanup"].get("forced") is not False:
                    receipt["technical_integration"] = "FAILED"
        except Exception as exc:
            cleanup_error = exc
            receipt.update(technical_integration="FAILED", cleanup={"state": "unverified",
                "failure_type": type(exc).__name__, "launcher_pid": process.pid})
        try:
            after_main = file_hash(main_state) if main_state.exists() else None
            receipt["main_state_unchanged"] = before_main == after_main
            if main_healthy:
                with httpx.Client(timeout=3, trust_env=False) as client:
                    receipt["main_health_preserved"] = client.get("http://127.0.0.1:8765/health").json().get("status") == "ok"
        except (OSError, httpx.HTTPError, ValueError):
            receipt["main_preservation_check"] = "unavailable"
            receipt["technical_integration"] = "FAILED"
        if not receipt.get("main_state_unchanged", False) or not receipt.get("main_health_preserved", True):
            receipt["technical_integration"] = "FAILED"
        write_json(base / "fixture-receipt.json", receipt)
        if cleanup_error:
            raise cleanup_error
    assert receipt["main_state_unchanged"] is True
    assert receipt.get("main_health_preserved", True) is True
    assert receipt["cleanup"]["state"] == "stopped" and not receipt["cleanup"]["forced"]
    print("Native integration PASS; P6 observation INCOMPLETE (five seconds only).", flush=True)


if __name__ == "__main__":
    cli()
